// Cloudflare Worker management. Wraps wrangler so nobody has to remember flags:
// the generated wrangler config always mirrors drift.config.json.
import { Command } from 'commander';
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Config, loadConfig, saveConfig, siteUrl } from '../../core/config.js';
import { loadEnv, secret } from '../../core/env.js';
import { PATHS } from '../../core/paths.js';
import { die, info, ok, printJson, warn } from '../ui.js';

export const GENERATED_TOML = join(PATHS.workerDir, 'wrangler.generated.toml');

export function renderWranglerConfig(config: Config, opts: { local?: boolean } = {}): string {
  const vars: Record<string, string> = {
    __D1_DATABASE_ID__: config.worker.d1DatabaseId || (opts.local ? 'local-dev-db' : ''),
    __SITE_URL__: siteUrl(config),
    __DEALER_NAME__: config.dealer.name,
    __TELEGRAM_CHAT_ID__: config.contact.telegramChatId,
    __CONTACT_EMAIL__: config.contact.email,
    __CONTACT_FROM_EMAIL__: config.contact.fromEmail,
    __CONTACT_METHODS__: config.contact.methods.join(','),
    __IP_MODE__: config.analytics.ipMode,
  };
  let toml = readFileSync(PATHS.wranglerToml, 'utf8').replace(/^name = .*$/m, `name = "${config.worker.name}"`);
  for (const [k, v] of Object.entries(vars)) toml = toml.split(k).join(v.replace(/"/g, '\\"'));
  return toml;
}

function writeGenerated(config: Config, local = false): string {
  if (!local && !config.worker.d1DatabaseId) die('worker.d1DatabaseId is empty. Create the DB first: drift worker create-db');
  writeFileSync(GENERATED_TOML, `# GENERATED by drift from worker/wrangler.toml + drift.config.json. Do not edit.\n` + renderWranglerConfig(config, { local }));
  return GENERATED_TOML;
}

function wrangler(args: string[], extraEnv: Record<string, string> = {}): number {
  loadEnv();
  const bin = join(PATHS.root, 'node_modules', '.bin', 'wrangler');
  const res = spawnSync(bin, args, { stdio: 'inherit', cwd: PATHS.workerDir, env: { ...process.env, ...extraEnv } });
  return res.status ?? 1;
}

const cfEnv = (): Record<string, string> => ({ ...(secret('CLOUDFLARE_API_TOKEN') ? { CLOUDFLARE_API_TOKEN: secret('CLOUDFLARE_API_TOKEN')! } : {}), ...(secret('CLOUDFLARE_ACCOUNT_ID') ? { CLOUDFLARE_ACCOUNT_ID: secret('CLOUDFLARE_ACCOUNT_ID')! } : {}) });

export async function deployWorker(): Promise<void> {
  const config = loadConfig();
  const file = writeGenerated(config);
  info(`deploying worker "${config.worker.name}" with vars from drift.config.json`);
  const code = wrangler(['deploy', '--config', file], cfEnv());
  if (code !== 0) die('wrangler deploy failed');
  ok('worker deployed. Secrets are managed separately: drift worker secrets');
}

export function registerWorker(program: Command): void {
  const cmd = program.command('worker').description('Cloudflare Worker: dev server, D1 schema, secrets, health');

  cmd.command('dev')
    .description('Run the worker locally (local D1, applies schema). Pair with `drift serve` and set worker.url=http://localhost:8787')
    .option('-p, --port <port>', 'port', '8787')
    .option('--var <kv...>', 'extra vars KEY:VALUE (e.g. TELEGRAM_API_BASE:http://localhost:8099)')
    .action((opts) => {
      const file = writeGenerated(loadConfig(), true);
      wrangler(['d1', 'execute', 'DB', '--local', '--file', join(PATHS.workerDir, 'schema.sql'), '--config', file]);
      const secretsEnv: Record<string, string> = {};
      for (const name of ['TELEGRAM_BOT_TOKEN', 'RESEND_API_KEY', 'TURNSTILE_SECRET_KEY'] as const) if (secret(name)) secretsEnv[name] = secret(name)!;
      // wrangler dev reads .dev.vars for secrets; write it from .env so local == prod behaviour.
      const devVars = { ADMIN_TOKEN: secret('DRIFT_ADMIN_TOKEN') ?? 'dev-admin-token', DASHBOARD_TOKEN: secret('DRIFT_DASHBOARD_TOKEN') ?? 'dev-dash-token', ...secretsEnv };
      writeFileSync(join(PATHS.workerDir, '.dev.vars'), Object.entries(devVars).map(([k, v]) => `${k}="${v}"`).join('\n') + '\n');
      const args = ['dev', '--config', file, '--port', String(opts.port), '--local'];
      for (const kv of opts.var ?? []) args.push('--var', kv);
      info(`admin token for local dev: ${devVars.ADMIN_TOKEN}  dashboard token: ${devVars.DASHBOARD_TOKEN}`);
      process.exit(wrangler(args));
    });

  cmd.command('create-db')
    .description('Create the D1 database on Cloudflare and store its id in drift.config.json')
    .action(() => {
      const config = loadConfig();
      loadEnv();
      const res = spawnSync(join(PATHS.root, 'node_modules', '.bin', 'wrangler'), ['d1', 'create', config.worker.name], { encoding: 'utf8', cwd: PATHS.workerDir, env: { ...process.env, ...cfEnv() } });
      process.stdout.write(res.stdout ?? '');
      process.stderr.write(res.stderr ?? '');
      const m = /database_id\s*=\s*"([0-9a-f-]{36})"/.exec(res.stdout ?? '');
      if (!m) die('could not find database_id in wrangler output; paste it with: drift config set worker.d1DatabaseId <id>');
      config.worker.d1DatabaseId = m[1]!;
      saveConfig(config);
      ok(`worker.d1DatabaseId = ${m[1]}`);
    });

  cmd.command('migrate')
    .description('Apply worker/schema.sql to D1 (remote by default, --local for dev)')
    .option('--local', 'local dev database')
    .action((opts) => {
      const file = writeGenerated(loadConfig(), Boolean(opts.local));
      const code = wrangler(['d1', 'execute', 'DB', opts.local ? '--local' : '--remote', '--file', join(PATHS.workerDir, 'schema.sql'), '--config', file], cfEnv());
      if (code !== 0) die('migration failed');
      ok('schema applied');
    });

  cmd.command('secrets')
    .description('Push secrets from .env to the deployed worker (TELEGRAM_BOT_TOKEN, RESEND_API_KEY, TURNSTILE_SECRET_KEY, ADMIN_TOKEN, DASHBOARD_TOKEN)')
    .action(() => {
      const file = writeGenerated(loadConfig());
      const map: Record<string, string | undefined> = {
        TELEGRAM_BOT_TOKEN: secret('TELEGRAM_BOT_TOKEN'), RESEND_API_KEY: secret('RESEND_API_KEY'), TURNSTILE_SECRET_KEY: secret('TURNSTILE_SECRET_KEY'),
        ADMIN_TOKEN: secret('DRIFT_ADMIN_TOKEN'), DASHBOARD_TOKEN: secret('DRIFT_DASHBOARD_TOKEN'),
      };
      const present = Object.fromEntries(Object.entries(map).filter(([, v]) => v)) as Record<string, string>;
      for (const name of Object.keys(map)) if (!present[name]) warn(`${name} not set in .env — skipped`);
      if (!Object.keys(present).length) die('nothing to push');
      const code = wrangler(['secret', 'bulk', '--config', file], { ...cfEnv(), WRANGLER_SECRET_BULK_JSON: JSON.stringify(present) });
      if (code !== 0) {
        // older wrangler: fall back to a temp file via stdin
        const res = spawnSync(join(PATHS.root, 'node_modules', '.bin', 'wrangler'), ['secret', 'bulk', '--config', file], { input: JSON.stringify(present), stdio: ['pipe', 'inherit', 'inherit'], cwd: PATHS.workerDir, env: { ...process.env, ...cfEnv() } });
        if (res.status !== 0) die('wrangler secret bulk failed');
      }
      ok(`pushed ${Object.keys(present).join(', ')}`);
    });

  cmd.command('health')
    .description('Call the deployed worker /health')
    .action(async () => {
      const url = loadConfig().worker.url.replace(/\/+$/, '');
      if (!url) die('worker.url not set');
      const res = await fetch(`${url}/health`);
      printJson(await res.json());
    });

  cmd.command('render-config').description('Print the generated wrangler config').action(() => console.log(renderWranglerConfig(loadConfig(), { local: true })));
}
